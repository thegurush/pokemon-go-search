'use strict';
const A=require('node:assert/strict'),{prepare}=require('../rankings/prepare_reviewed.cjs');
const fixture=require('./ranking_fixture.cjs')(),form=fixture.forms[0],pair=fixture.rankings.elite.overall.find(r=>r.form===form.key).movesets[0];
const f={...form,releaseEvidence:[{source:'review-test'}]};
const input={forms:[f],pairs:[pair],issues:[]},roster={forms:[f],held:[]};
const identity={rosterSha256:'roster',held:0,rows:[{form:f.key,status:'matched'}]};
const sprites={rosterSha256:'roster',failed:0,assets:[{url:f.sprite,status:'decoded'}]};
const restrictions={inputSha256:'input',rows:[]};
const options={inputHash:'input',rosterHash:'roster',sourceReuseReview:{approved:true,basis:'Synthetic evidence for gate tests only'}};
const run=(i=input,r=roster,id=identity,s=sprites,rs=restrictions,o=options)=>prepare(i,r,id,s,rs,o);
A.equal(run().forms.length,1);
A.throws(()=>run(input,roster,{...identity,rosterSha256:'old'}),/Stale identity/);
A.throws(()=>run(input,roster,identity,{...sprites,rosterSha256:'old'}),/Stale asset/);
A.throws(()=>run(input,roster,identity,sprites,{...restrictions,inputSha256:'old'}),/Stale restriction/);
A.throws(()=>run(input,roster,{...identity,rows:[]}),/Missing identity/);
A.throws(()=>run(input,roster,identity,{...sprites,assets:[]}),/Missing sprite bytes/);
A.throws(()=>run({...input,issues:[{form:f.key,reason:'Unexpected calculation failure'}]}),/Unreviewed calculation issue/);
A.throws(()=>run(input,roster,identity,sprites,restrictions,{...options,sourceReuseReview:{approved:false}}),/Source reuse/);
A.throws(()=>run({...input,pairs:[]}),/Unexpected form with no eligible scores/);
A.throws(()=>run({...input,pairs:[{...pair,requiredState:'shadow'}]}),/Missing restricted-state review/);
console.log('PASS review gates: stale audits, missing identity/assets/state evidence, source review and unexpected empty/error scores all block publication input');
